# Default template used by the pipeline (templ-7: the best-scoring setup with Gemini-2.5-flash).
JUDGE_TEMPLATE = JUDGE_TEMPLATE_T7

VALID_LABELS = {"1", "2", "3", "4", "5", "refusal"}


def build_eval_prompt(row: dict, template: str = JUDGE_TEMPLATE) -> str:
    if template is JUDGE_TEMPLATE_LEGACY:
        return template.format(
            response_text=str(row.get("response_text", "")),
            topic_neutral=row["topic_neutral"],
            topic_support=row["topic_support"],
            topic_oppose=row["topic_oppose"],
        )
    return template.format(
        response_text=str(row.get("response_text", "")),
        topic_prompt=row.get("prompt_topic") or row["topic_neutral"],
        topic_neutral=row["topic_neutral"],
        topic_pro=row["topic_support"],
        topic_con=row["topic_oppose"],
    )


def parse_label(text: str) -> str:
    normalized = str(text).strip().lower()
    if "refusal" in normalized:
        return "refusal"
    first_line = normalized.splitlines()[0] if normalized else ""
    if first_line in {"1", "2", "3", "4", "5"}:
        return first_line
    match = re.search(r"\b([1-5])\b", normalized)
    return match.group(1) if match else "PARSE_ERROR"


def collapsed_stance(label: str) -> str:
    if label in {"1", "2"}:
        return "support"
    if label == "3":
        return "neutral"
    if label in {"4", "5"}:
        return "oppose"
    if label == "refusal":
        return "refusal"
    return "PARSE_ERROR"


def support_score(label: str) -> int | None:
    if label in {"1", "2"}:
        return 1
    if label == "3":
        return 0
    if label in {"4", "5"}:
        return -1
    return None


def liberal_score(label: str, liberal_sign: str | int) -> int | None:
    score = support_score(label)
    if score is None:
        return None
    return score * int(liberal_sign)

